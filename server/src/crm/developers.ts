/**
 * Кто может значиться исполнителем проекта или задачи.
 *
 * Имена, а не учётные записи: исполнитель — человек из команды, своя учётка у
 * него есть не всегда, а отключение учётки не должно стирать его из истории
 * проектов. Список закрытый, потому что свободная строка превращает «Вадим»,
 * «вадим» и «Вадик» в трёх разных людей — и любая группировка по имени начинает
 * врать.
 *
 * Появился новый человек — добавьте строку здесь и в crm/src/lib/developers.ts.
 * Два файла, потому что сайт, CRM и API собираются раздельно; общий модуль
 * потребовал бы монорепо-воркспейс ради трёх строк.
 */
export const DEVELOPERS = ["Егор", "Вадим", "Камиль", "Тимур"] as const;

export type Developer = (typeof DEVELOPERS)[number];

export function isDeveloper(value: string): value is Developer {
  return (DEVELOPERS as readonly string[]).includes(value);
}
